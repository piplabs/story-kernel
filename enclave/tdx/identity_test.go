// FuzzParseTDXQuoteBody fuzzes parseTDXQuote with arbitrary byte slices to
// catch panics, infinite loops, and out-of-bounds reads. The seed corpus
// covers both valid V4/V5 quotes and various truncated/empty inputs so the
// fuzzer immediately exercises every length-check branch in the parser.
func FuzzParseTDXQuoteBody(f *testing.F) {
	// Valid V4 / V5 inputs.
	f.Add(synthV4TDXQuote([]byte{0}, defaultTestMRTD(), defaultTestRTMRs()))
	f.Add(synthV5TDXQuote([]byte{0}, defaultTestMRTD(), defaultTestRTMRs()))
	// Boundary truncations.
	f.Add([]byte{})
	f.Add(make([]byte, 1))
	f.Add(make([]byte, quoteHeaderSizeTDX-1))
	f.Add(make([]byte, quoteHeaderSizeTDX))
	f.Add(make([]byte, minQuoteSizeTD10-1))
	f.Add(make([]byte, minQuoteSizeTD10))
	// Random shape.
	f.Add(append([]byte{0xFF, 0xFF, 0xFF, 0xFF}, make([]byte, 700)...))

	f.Fuzz(func(t *testing.T, quote []byte) {
		parsed, err := parseTDXQuote(quote)
		if err != nil {
			if parsed != nil {
				t.Fatalf("parser returned both result and error: %v", err)
			}
			return
		}
		if len(parsed.MRTD) != sizeMeasurement {
			t.Fatalf("MRTD length = %d, want %d", len(parsed.MRTD), sizeMeasurement)
		}
		for i, r := range [][]byte{parsed.RTMR0, parsed.RTMR1, parsed.RTMR2, parsed.RTMR3} {
			if len(r) != sizeMeasurement {
				t.Fatalf("RTMR%d length = %d, want %d", i, len(r), sizeMeasurement)
			}
		}
		if len(parsed.ReportData) != tdxReportDataSize {
			t.Fatalf("ReportData length = %d, want %d", len(parsed.ReportData), tdxReportDataSize)
		}
	})
}

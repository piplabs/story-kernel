func TestCloneSlice_Independent(t *testing.T) {
	t.Parallel()
	a := []byte{1, 2, 3}
	b := cloneSlice(a)
	require.Equal(t, a, b)
	b[0] = 9
	require.NotEqual(t, a, b)
}

func TestCloneSlice_Empty(t *testing.T) {
	t.Parallel()
	out := cloneSlice(nil)
	require.NotNil(t, out)
	require.Empty(t, out)
}

func TestIsZero(t *testing.T) {
	t.Parallel()
	require.True(t, isZero(nil))
	require.True(t, isZero([]byte{0, 0, 0}))
	require.False(t, isZero([]byte{0, 0, 1}))
}

// =============================================================================
// V4 fast-path coverage with a production-shape quote.
//
// Synthetic quotes generated by synthV4TDXQuote are intentionally minimal
// (header + body only) and do NOT pass abi.QuoteToProto's QuoteMinSize
// check, so they always exercise the parseTDXQuoteManual fallback. The
// fixture below is a real Sapphire Rapids TDX quote (full DCAP envelope)
// used to exercise the parseTDXQuoteV4 success path. See testdata/README.md
// for the source and licensing.
// =============================================================================

// TestParseTDXQuoteV4_RealQuote ensures the abi.QuoteToProto fast path
// returns a parsedTDXQuote whose measurement fields have the documented
// shapes (48B MRTD, 48B RTMR0..3, 64B ReportData) and whose TeeType matches
// teeTypeTDX. It also asserts CodeCommitment-relevant fields are non-zero,
// matching what real TDX hardware emits.
func TestParseTDXQuoteV4_RealQuote(t *testing.T) {
	t.Parallel()
	raw, err := os.ReadFile(filepath.Join("testdata", "tdx_prod_quote_SPR_E4.dat"))
	require.NoError(t, err)

	parsed, err := parseTDXQuoteV4(raw)
	require.NoError(t, err)
	require.Equal(t, uint16(4), parsed.Version)
	require.Equal(t, teeTypeTDX, parsed.TeeType)
	require.Len(t, parsed.MRTD, sizeMeasurement)
	require.Len(t, parsed.RTMR0, sizeMeasurement)
	require.Len(t, parsed.RTMR1, sizeMeasurement)
	require.Len(t, parsed.RTMR2, sizeMeasurement)
	require.Len(t, parsed.RTMR3, sizeMeasurement)
	require.Len(t, parsed.ReportData, tdxReportDataSize)
	require.False(t, isZero(parsed.MRTD), "real TDX MRTD must not be all-zero")
}

// TestParseTDXQuote_RealQuote_DispatchesToV4Path confirms the top-level
// parseTDXQuote dispatcher selects the V4 fast path for a real quote (i.e.,
// abi.QuoteToProto succeeds, and the manual fallback is not reached). The
// observable signature is the same parsed measurements; this test exists so
// a future regression that broke the fast path (e.g., a constant change or
// abi behavior change) would not silently re-route every real quote through
// the manual parser without a coverage signal.
func TestParseTDXQuote_RealQuote_DispatchesToV4Path(t *testing.T) {
	t.Parallel()
	raw, err := os.ReadFile(filepath.Join("testdata", "tdx_prod_quote_SPR_E4.dat"))
	require.NoError(t, err)

	parsed, err := parseTDXQuote(raw)
	require.NoError(t, err)
	require.Equal(t, uint16(4), parsed.Version)
	require.Equal(t, teeTypeTDX, parsed.TeeType)
	require.Len(t, parsed.MRTD, sizeMeasurement)
}


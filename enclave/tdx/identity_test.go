func TestParseTDXQuote_WrongTeeType(t *testing.T) {
	t.Parallel()
	q := synthV4TDXQuote(nil, defaultTestMRTD(), defaultTestRTMRs())
	// Overwrite tee_type to SGX value.
	binary.LittleEndian.PutUint32(q[quoteOffTeeType:], teeTypeSGX)
	_, err := parseTDXQuote(q)
	require.ErrorContains(t, err, "not a TDX quote")
}


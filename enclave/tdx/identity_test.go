func TestParseTDXQuote_V4Valid(t *testing.T) {
	t.Parallel()
	wantMRTD := defaultTestMRTD()
	wantRTMRs := defaultTestRTMRs()
	q := synthV4TDXQuote([]byte("rd"), wantMRTD, wantRTMRs)

	parsed, err := parseTDXQuote(q)
	require.NoError(t, err)
	require.Equal(t, uint16(4), parsed.Version)
	require.Equal(t, teeTypeTDX, parsed.TeeType)
	require.Equal(t, wantMRTD, parsed.MRTD)
	require.Equal(t, wantRTMRs[0], parsed.RTMR0)
	require.Equal(t, wantRTMRs[1], parsed.RTMR1)
	require.Equal(t, wantRTMRs[2], parsed.RTMR2)
	require.Equal(t, wantRTMRs[3], parsed.RTMR3)
	require.Len(t, parsed.ReportData, tdxReportDataSize)
	require.Equal(t, byte('r'), parsed.ReportData[0])
	require.Equal(t, byte('d'), parsed.ReportData[1])
}

